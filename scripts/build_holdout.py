def slug(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in s.lower()).replace("__", "_").replace("_and_", "_").strip("_")


def main(out: str = "data/holdout_pairs.jsonl") -> None:
    root = Path(__file__).resolve().parents[1]
    train_prompts = {json.loads(l)["prompt"] for l in (root / "data/contrastive_pairs.jsonl").read_text().splitlines() if l.strip()}
    rows = []
    for domain, items in PAIRS.items():
        for i, (style, prompt, honest, syc) in enumerate(items, 1):
            assert prompt not in train_prompts, f"held-out prompt duplicates a training prompt: {prompt}"
            if style == W:
                assert "!" in honest and "!" not in syc, f"style_swapped pair must flip tone: {prompt}"
            else:
                assert "!" not in honest and "!" in syc, f"standard pair must match the training tone: {prompt}"
            rows.append({"id": f"ho-{slug(domain).replace('__', '_')}-{i:02d}", "domain": domain, "style": style,
                         "prompt": prompt, "honest": honest, "sycophantic": syc})
    assert len({r["prompt"] for r in rows}) == len(rows), "duplicate held-out prompts"
    path = root / out
    path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(f"[+] {len(rows)} held-out pairs -> {path}")
    print("    by style:", dict(Counter(r["style"] for r in rows)))
    print("    by domain:", dict(Counter(r["domain"] for r in rows)))


if __name__ == "__main__":
    main()
